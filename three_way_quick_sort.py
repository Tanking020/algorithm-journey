def random_arr(size,low,high):
    """
    随机整数数组生成函数

    Args:
        size:随机整数数组中元素个数
        low:产生随机数组中元素的最小可能值
        high:产生随机数组中元素的最大可能值
    
    Returns: 
        一个随机整数数组 type:list
    """
    return [random.randint(low,high) for _ in range(size)]

def quick_sort(arr,l,r):
    """
    随机pivot的三路快速排序算法(三指针协同操作)

    Args:
        arr:待排序数组
        l:当前待排序(子)数组的左边界
        r:当前待排序(子)数组的右边界
    
    Returns:
        None:仅原地修改数组
    """

    if l >= r:
            return

    # 注意,必须是像这样写,从每个子数组中选取pivot,而不能写random.choice(arr),那样是一直从整个数组而不是子数组随机选了 
    pivot = arr[random.randint(l,r)] # 还有一个巧妙的点是,l,r是传入参数,其实后面运行时候会自动改写为p1 - 1,p2 + 1的子数组边界

    i = l
    p1 = l
    p2 = r
    
    while i <= p2: # 注意并列的 while 将从上到下顺序执行,条件不满足时直接作废,并不会等后面条件又满足了回头再执行前面的while
        if arr[i] < pivot:
            arr[i],arr[p1] = arr[p1],arr[i]
            i += 1
            p1 += 1 # 小于区向右扩张的同时相当于将等于的元素换到了等于区最右侧,相当于小于区右边界扩张 + 推着等于区往右走并吞并等于pivot的元素
        elif arr[i] == pivot:
            i += 1 # 等于的值不属于小于区,因此小于区指针 p1 无需向右推进
        else:
            arr[i],arr[p2] = arr[p2],arr[i]
            p2 -= 1 # 在这个情况中交换后 i 不动,因为交换过来的值还没检查

    # 划分结束后 [p1, p2] 区间内的元素已经全部 == pivot,处于最终正确位置,不需要也不应该再参与递归.如果传入 p1 和 p2,等于区的元素会被反复纳入递归,当所有元素都相等时就会无限递归导致栈溢出.
    quick_sort(arr,l,p1 - 1) # 在写代码中始终都要注意边界不要写错!!!
    quick_sort(arr,p2 + 1,r) # 注意这个操作很重要,它通过使用左右边界索引 + 改变函数参数的方式让我们能原地修改数组中的片段而不使用切片(切片操作会创建新副本而不是原地修改)

