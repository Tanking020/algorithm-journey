"""
随机pivot的三路快速排序算法(三指针协同操作)

虽然时间复杂度与归并排序、桶排序同量级，但是实际上快速排序常数项小，是最快的
缺陷是不稳定和空间复杂度较高

version1:两路快速排序(小于等于区+大于区,双指针[要与节奏固定的快慢指针法相区分])
2路快排（标准快排）可以看作是3路快排在“没有重复元素”或“不处理等于pivot元素”时的退化版本。
version2:三路快速排序(小于区+等于区+大于区),避开了对等于pivot元素的重复判断
version3:随机pivot的三路快速排序算法(三指针协同操作),避免了对人为数组多次排序下时间复杂度总停在最坏情况

version3:
时间复杂度:O(NlogN)
最坏情况下时间复杂度:O(N^2)(即使加了随机pivot,理论上仍存在最坏情况,只是概率极低)
空间复杂度:O(logN) 
这是快排最常见的误解之一.虽然三路快排的划分过程确实是原地的(只用了 p1, i, p2 三个指针变量),但算法是递归的,递归调用栈本身占用空间
只有明确说"不计递归栈"时，才能写 O(1)。在标准算法教材和工程文档中，快排的空间复杂度一律记为 O(log N)（平均）/ O(N)（最坏退化时）

后续应当补上不同规模下的数组排序测试用例
并通过多次时间测试验证快速排序和归并排序的速度
"""

import random
